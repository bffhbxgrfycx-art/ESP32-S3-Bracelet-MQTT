#pragma once

#include <stdbool.h>

/* ============================================================
 * 电源/背光管理：自动息屏 + 亮屏触发
 * ------------------------------------------------------------
 * - backlight_wake()：点亮屏幕并重置无操作计时器
 * - power_mgmt_poll()：由周期任务每秒调用，检测是否超时自动息屏
 *   同时做抬腕检测（读全局 Accel，检测手腕翻转动作）
 * ============================================================ */

/* 点亮屏幕并重置无操作计时器（按键 / 抬腕 / 收到消息时调用） */
void backlight_wake(void);

/* 周期巡检：抬腕检测 + 无操作超时自动息屏。
 * 由 sensor_refresh_task 每 1 秒调用一次。 */
void power_mgmt_poll(void);

/* 判断屏幕当前是否点亮 */
bool power_mgmt_is_on(void);
